CVD={'protan':[[0.152286,1.052583,-0.204868],[0.114503,0.786281,0.099216],[-0.003882,-0.048116,1.051998]],
     'deutan':[[0.367322,0.860646,-0.227968],[0.280085,0.672501,0.047413],[-0.011820,0.042940,0.968881]],
     'tritan':[[1.255528,-0.076749,-0.178779],[-0.078411,0.930809,0.147602],[0.004733,0.691367,0.303900]]}
def sim(h,kind):
    if kind=='normal': return hx(h)
    r,g,b=[lin(x) for x in hx(h)]; M=CVD[kind]
    return tuple(unlin(M[i][0]*r+M[i][1]*g+M[i][2]*b) for i in range(3))
def de(a,b,kind='normal'): return de00(lab_from_rgb(sim(a,kind)),lab_from_rgb(sim(b,kind)))
